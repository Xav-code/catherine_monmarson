/**
 * Writes public/contact.php and public/.htaccess for Apache hosts (DreamHost).
 *
 * The PHP handler is generated rather than committed by hand so the addresses
 * come from data/to-confirm.json and there is one place to change them.
 * It is only emitted when forms.provider is "php"; otherwise any stale copy is
 * removed, so a Netlify or Cloudflare deploy never ships a dead endpoint.
 *
 * Runs automatically as part of `npm run build`.
 */
import { writeFile, rm, mkdir } from 'node:fs/promises';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const PUBLIC = path.join(ROOT, 'public');
const tc = JSON.parse(await readFile(path.join(ROOT, 'data/to-confirm.json'), 'utf8'));

await mkdir(PUBLIC, { recursive: true });

const php = path.join(PUBLIC, 'contact.php');

if (tc.forms.provider !== 'php') {
  await rm(php, { force: true });
  console.log(`form handler: provider is "${tc.forms.provider}" — contact.php not generated`);
} else {
  const to = tc.contact.email;
  const from = tc.forms.mailFrom;
  if (!to) console.warn('form handler: contact.email is empty — enquiries have nowhere to go');
  if (!from) console.warn('form handler: forms.mailFrom is empty — the host will reject the mail');

  /* PHP's mail() hands the message to the local MTA. Two rules matter:
     From: must be an address on this domain or shared hosts refuse it, and no
     user input may reach a header unescaped or it becomes header injection. */
  const source = `<?php
/**
 * Enquiry handler for ${new URL(tc.site.url).hostname} — generated by
 * scripts/build-form-handler.mjs. Do not edit here; edit data/to-confirm.json.
 */
declare(strict_types=1);

const MAIL_TO   = ${JSON.stringify(to)};
const MAIL_FROM = ${JSON.stringify(from)};
const MAX_LEN   = 5000;

function fail(string $lang): never {
    $back = $lang === 'en' ? '/en/contact' : '/contact';
    header('Location: ' . $back . '?error=1', true, 303);
    exit;
}

/** Headers must never contain a line break: that is how injection works. */
function oneLine(string $v): string {
    return trim(str_replace(["\\r", "\\n", "\\0"], ' ', $v));
}

if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') {
    header('Location: /contact', true, 303);
    exit;
}

$lang = (($_POST['lang'] ?? 'fr') === 'en') ? 'en' : 'fr';

// Bots fill every field they find; people never see this one.
if (!empty($_POST['bot-field'])) {
    header('Location: ' . ($lang === 'en' ? '/en/thank-you' : '/merci'), true, 303);
    exit;
}

$name    = oneLine(substr((string)($_POST['name'] ?? ''), 0, 200));
$email   = oneLine(substr((string)($_POST['email'] ?? ''), 0, 200));
$subject = oneLine(substr((string)($_POST['subject'] ?? ''), 0, 100));
$about   = oneLine(substr((string)($_POST['about'] ?? ''), 0, 300));
$ref     = oneLine(substr((string)($_POST['ref'] ?? ''), 0, 40));
$message = substr((string)($_POST['message'] ?? ''), 0, MAX_LEN);

if ($name === '' || $message === '' || !filter_var($email, FILTER_VALIDATE_EMAIL)) {
    fail($lang);
}

$subjects = [
    'acquire'    => 'Acquisition',
    'visit'      => "Visite d'atelier",
    'commission' => 'Commande',
    'workshop'   => 'Ateliers',
    'press'      => 'Presse',
    'other'      => 'Message',
];
$label = $subjects[$subject] ?? 'Message';
$mailSubject = '[Site] ' . $label . ($about !== '' ? ' — ' . $about : '');

$body = "De      : {$name} <{$email}>\\n"
      . "Objet   : {$label}\\n"
      . ($about !== '' ? "Œuvre   : {$about}\\n" : '')
      . ($ref   !== '' ? "Réf.    : CM-{$ref}\\n" : '')
      . "Langue  : {$lang}\\n"
      . "Reçu le : " . date('d/m/Y H:i') . "\\n"
      . str_repeat('-', 50) . "\\n\\n"
      . $message . "\\n";

$headers = [
    'From: Site Catherine Monmarson <' . MAIL_FROM . '>',
    'Reply-To: ' . oneLine($name) . ' <' . $email . '>',
    'Content-Type: text/plain; charset=UTF-8',
    'X-Mailer: PHP/' . phpversion(),
];

$sent = @mail(
    MAIL_TO,
    '=?UTF-8?B?' . base64_encode($mailSubject) . '?=',
    $body,
    implode("\\r\\n", $headers)
);

if (!$sent) {
    fail($lang);
}

header('Location: ' . ($lang === 'en' ? '/en/thank-you' : '/merci'), true, 303);
exit;
`;

  await writeFile(php, source, 'utf8');
  console.log(`form handler: public/contact.php → ${to || '(no recipient set)'}`);
}

/* ------------------------------------------------------------- .htaccess */

/* Netlify reads netlify.toml, Cloudflare reads _redirects and _headers, and
   Apache reads none of them — so the same rules are restated here. Harmless
   on the other two hosts, which ignore the file. */
const htaccess = `# Generated by scripts/build-form-handler.mjs — do not edit by hand.

Options -Indexes
DirectoryIndex index.html

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Permissions-Policy "geolocation=(), microphone=(), camera=()"
  <FilesMatch "\\.(avif|webp|jpg|jpeg|png|svg|woff2|css|js)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.html$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml
</IfModule>

AddDefaultCharset UTF-8
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # French is the default language and lives at the root.
  RewriteRule ^fr/(.*)$ /$1 [R=301,L]

  # Serve /oeuvres as /oeuvres/index.html without an extra redirect hop.
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteCond %{REQUEST_FILENAME}/index.html -f
  RewriteRule ^(.*)$ /$1/index.html [L]
</IfModule>
`;

await writeFile(path.join(PUBLIC, '.htaccess'), htaccess, 'utf8');
console.log('form handler: public/.htaccess');

/* robots.txt must name the real sitemap, so it follows site.url too. */
const site = String(tc.site.url).replace(/\/$/, '');
await writeFile(
  path.join(PUBLIC, 'robots.txt'),
  `User-agent: *
Allow: /

Sitemap: ${site}/sitemap-index.xml
`,
  'utf8'
);
console.log(`form handler: public/robots.txt → ${site}`);
